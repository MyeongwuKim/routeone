/**
 * 용도:
 * Xcode 빌드에 사용할 Native 환경값을 선택한 env 파일과 맞춘다.
 *
 * 동작 방식:
 * env 파일 값을 셸에서 안전하게 읽을 수 있는 형태로 변환해 `.xcode.env.local`에
 * 저장하고, Xcode 번들 단계가 다른 env 파일을 추가로 읽지 않도록 설정한다.
 */
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { readEnvFile } from "./env-file.mjs";

const nativeRoot = path.resolve(fileURLToPath(new URL("..", import.meta.url)));
const envFileName = process.argv[2]?.trim();
const appVariant = process.argv[3]?.trim();

if (!envFileName || !["none", "dev", "prod"].includes(appVariant)) {
  console.error(
    "[xcode-env] env 파일 경로와 앱 variant(none, dev, prod)가 필요합니다."
  );
  process.exit(1);
}

const envFilePath = path.resolve(nativeRoot, envFileName);

if (!existsSync(envFilePath)) {
  console.error(`[xcode-env] ${envFileName} 파일이 없습니다.`);
  process.exit(1);
}

function quoteShellValue(value) {
  return `'${String(value).replaceAll("'", `'"'"'`)}'`;
}

const fileEnv = readEnvFile(envFilePath);
if (appVariant === "none") {
  // 로컬 실행에서 셸로 지정한 값도 Metro와 Xcode에서 동일하게 사용한다.
  for (const key of [...Object.keys(fileEnv), "EXPO_PUBLIC_GRAPHQL_ENDPOINT"]) {
    if (process.env[key] !== undefined) fileEnv[key] = process.env[key];
  }
}

const xcodeEnv = {
  ...fileEnv,
  NODE_BINARY: process.execPath,
  NODE_ENV: "production",
  EXPO_NO_DOTENV: "1",
  ROUTEONE_ENV_FILE: envFileName,
  ROUTEONE_BUILD_PLATFORM: "ios",
  APP_VARIANT: appVariant,
  EXPO_PUBLIC_APP_VARIANT: appVariant,
};
const xcodeEnvPath = path.join(nativeRoot, "ios/.xcode.env.local");
const source = [
  "# Generated by scripts/sync-xcode-env.mjs.",
  ...Object.entries(xcodeEnv).map(
    ([key, value]) => `export ${key}=${quoteShellValue(value)}`
  ),
  "",
].join("\n");

mkdirSync(path.dirname(xcodeEnvPath), { recursive: true });
writeFileSync(xcodeEnvPath, source, "utf8");

console.log(
  `[xcode-env] ${envFileName} 기준으로 ${appVariant} Xcode 빌드 환경을 설정했습니다.`
);
