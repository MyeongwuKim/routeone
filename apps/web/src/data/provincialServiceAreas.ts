type RegionEntry = readonly [label: string, tourCode: string, adminCode: string, lat: number, lng: number];

/** 관광공사 시·군·구 목록과 경계 코드의 대응표로 권역 설정을 만든다. */
function createArea(
  id: ServiceAreaId,
  label: string,
  tourAreaCode: string,
  tatsAreaCode: string,
  defaultLabel: string,
  entries: readonly RegionEntry[]
): ServiceArea {
  const regions = entries.map(([label, sigunguCode, adminCode, lat, lng]) => ({
    label, sigunguCode, adminCode, center: { lat, lng },
  }));
  const defaultRegion = regions.find((region) => region.label === defaultLabel) ?? regions[0];
  return {
    id, label, tourAreaCode, tatsAreaCode,
    center: defaultRegion.center, defaultRegion, regions,
    hasBoundaryAsset: true,
    boundaryAssetPath: "/service-region-boundary.json",
    hasFestivalSource: true,
  };
}

